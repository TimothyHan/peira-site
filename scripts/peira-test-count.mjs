// The metrics strip shows "tests on the tool itself". That number went stale three releases
// running because it was a string in a data file. It is now generated at build time from a real
// test run — never typed, never stale. Two sources, in order:
//   1. PEIRA_TEST_COUNT in the environment — CI sets it after running the tool's suite
//   2. a checkout of the tool at $PEIRA_REPO or ../peira — run its suite and read `# tests N`
// Neither present → the build fails with instructions. A wrong number is worse than no build.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '..', 'src', 'data', 'generated', 'test-count.ts');

function fromEnv() {
  const v = process.env.PEIRA_TEST_COUNT;
  if (!v) return null;
  if (!/^\d+$/.test(v)) throw new Error(`PEIRA_TEST_COUNT must be an integer, got ${JSON.stringify(v)}`);
  return { count: Number(v), source: 'env' };
}

function fromSibling() {
  const repo = process.env.PEIRA_REPO ?? resolve(here, '..', '..', 'peira');
  if (!existsSync(resolve(repo, 'package.json'))) return null;
  process.stderr.write(`peira-test-count: running the tool's suite in ${repo} …\n`);
  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  const r = spawnSync(npm, ['test'], { cwd: repo, encoding: 'utf8', shell: process.platform === 'win32' });
  const text = `${r.stdout ?? ''}\n${r.stderr ?? ''}`;
  const m = /^# tests (\d+)$/m.exec(text);
  const fail = /^# fail (\d+)$/m.exec(text);
  if (!m) throw new Error(`could not find "# tests N" in the tool's test output (exit ${r.status})`);
  if (fail && Number(fail[1]) > 0) throw new Error(`the tool's suite has ${fail[1]} failing test(s); refusing to publish a count from a red run`);
  return { count: Number(m[1]), source: `sibling ${repo}` };
}

const resolved = fromEnv() ?? fromSibling();
if (!resolved) {
  console.error(
    'peira-test-count: no source for the test count.\n' +
    '  set PEIRA_TEST_COUNT=<n> (CI does this after running the tool\'s suite), or\n' +
    '  check out TimothyHan/peira beside this repo (../peira) or point PEIRA_REPO at it.',
  );
  process.exit(1);
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// GENERATED by scripts/peira-test-count.mjs — do not edit, do not commit.\n// source: ${resolved.source} · ${new Date().toISOString()}\nexport const PEIRA_TEST_COUNT = ${resolved.count};\n`);
console.log(`peira-test-count: ${resolved.count} (${resolved.source}) → src/data/generated/test-count.ts`);
